    private static (Regex, string) Format(string expression, string translation) =>
        (new Regex(expression, RegexOptions.CultureInvariant | RegexOptions.NonBacktracking), translation);

    public static string Translate(string sourceText)
    {
        if (English.TryGetValue(sourceText, out var text)) return InterfaceText.Get(sourceText, text);
        foreach (var (rule, english) in StatusFormats)
            if (rule.IsMatch(sourceText)) return InterfaceText.Get(sourceText, rule.Replace(sourceText, english, 1));
        return sourceText;
    }
